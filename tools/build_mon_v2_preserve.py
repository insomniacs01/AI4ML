def insert_paragraph_after(paragraph: Paragraph, text: str = "", style: str | None = None) -> Paragraph:
    new_p = OxmlElement("w:p")
    paragraph._p.addnext(new_p)
    new_para = Paragraph(new_p, paragraph._parent)
    if style:
        new_para.style = style
    if text:
        new_para.add_run(text)
    return new_para


def insert_paragraphs_after(paragraph: Paragraph, items: list[tuple[str, str | None]]) -> Paragraph:
    last = paragraph
    for text, style in items:
        last = insert_paragraph_after(last, text, style)
    return last


def find_paragraph(doc: Document, expected: str) -> Paragraph:
    for para in doc.paragraphs:
        if para.text.strip() == expected:
            return para
    raise ValueError(f"Paragraph not found: {expected}")


def replace_paragraph_text(doc: Document, old: str, new: str) -> None:
    para = find_paragraph(doc, old)
    para.text = new


